const cloud = require('wx-server-sdk')
cloud.init({ env: cloud.DYNAMIC_CURRENT_ENV })
const db = cloud.database()
const _ = db.command

/**
 * Daily 23:00 timer — backfill banquet purchase & income for today+past 3 days.
 * Skips reservations that already have linked records (manual or auto).
 */
exports.main = async (event, context) => {
  try {
    // 1. Load settings
    const settingsRes = await db.collection('settings').get()
    const settings = {}
    ;(settingsRes.data || []).forEach(s => { settings[s.key] = s.value })

    if (!settings.serviceChargeEnabled) {
      console.log('[autoSync] 服务费模式未开启，跳过')
      return { skipped: true, reason: 'serviceCharge disabled' }
    }

    const enabledDate = settings.serviceChargeEnabledDate
    const chargeNoon = Number(settings.serviceChargeNoon) || 0
    const chargeNight = Number(settings.serviceChargeNight) || 0

    // 2. Calculate date range: today-3 to today
    const now = new Date()
    const today = now.getFullYear() + '-' +
      String(now.getMonth() + 1).padStart(2, '0') + '-' +
      String(now.getDate()).padStart(2, '0')

    const past = new Date(now)
    past.setDate(past.getDate() - 3)
    const threeDaysAgo = past.getFullYear() + '-' +
      String(past.getMonth() + 1).padStart(2, '0') + '-' +
      String(past.getDate()).padStart(2, '0')

    // 3. Find eligible reservations
    const startDate = new Date(threeDaysAgo + 'T00:00:00')
    const endDate = new Date(today + 'T23:59:59')

    const resvRes = await db.collection('reservation')
      .where({
        date: _.gte(startDate).and(_.lte(endDate)),
        status: 'confirmed',
        dishPrice: _.gt(0)
      })
      .get()

    const reservations = resvRes.data || []
    console.log('[autoSync] 找到 ' + reservations.length + ' 条待处理预约')

    let created = 0, skipped = 0

    for (const r of reservations) {
      const resDate = typeof r.date === 'object'
        ? r.date.getFullYear() + '-' + String(r.date.getMonth() + 1).padStart(2, '0') + '-' + String(r.date.getDate()).padStart(2, '0')
        : r.date

      // 4. Check serviceChargeEnabledDate
      if (resDate < enabledDate) {
        skipped++
        continue
      }

      const time = r.time || '中午'
      const charge = time === '中午' ? chargeNoon : chargeNight
      const dishPrice = Number(r.dishPrice) || 0

      // 5. Generate purchase (skip if any banquet purchase already linked)
      const purchaseRes = await db.collection('purchase')
        .where({
          sourceReservationId: r._id,
          category: 'banquet'
        })
        .get()

      if (!purchaseRes.data || purchaseRes.data.length === 0) {
        const customerName = r.customerName || ''
        const roomName = r.roomName || ''
        const remark = customerName + ' - ' + roomName

        await db.collection('purchase').add({
          data: {
            amount: dishPrice,
            category: 'banquet',
            date: resDate,
            remark: remark,
            item: '',
            sourceReservationId: r._id,
            autoGenerated: true,
            createdTime: db.serverDate()
          }
        })
        created++
      }

      // 6. Generate income (skip if any income already linked)
      const incomeRes = await db.collection('income')
        .where({ reservationId: r._id })
        .get()

      if (!incomeRes.data || incomeRes.data.length === 0) {
        const amount = dishPrice + charge

        await db.collection('income').add({
          data: {
            type: 'dining',
            amount: amount,
            date: resDate,
            source: r.customerName || '',
            reservationId: r._id,
            remark: '',
            calcMode: 'dishPrice',
            dishPrice: dishPrice,
            serviceCharge: charge,
            guestCount: r.guestCount || 0,
            standard: r.standard || 0,
            roomName: r.roomName || '',
            autoGenerated: true,
            createdTime: db.serverDate()
          }
        })

        // Mark hasIncome on reservation
        await db.collection('reservation').doc(r._id).update({
          data: { hasIncome: true }
        })
        created++
      }
    }

    console.log('[autoSync] 完成: created=' + created + ', skipped=' + skipped)
    return { created, skipped }
  } catch (err) {
    console.error('[autoSync] 错误:', err)
    return { error: err.message }
  }
}
